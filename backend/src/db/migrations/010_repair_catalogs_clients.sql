-- 3) Clientes del taller (no son cuentas de e-commerce).
CREATE TABLE repair_clients (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT NOT NULL,
  address    TEXT,
  dni        TEXT,
  email      TEXT,
  phone      TEXT,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX repair_clients_name_idx ON repair_clients (name);
CREATE INDEX repair_clients_dni_idx ON repair_clients (dni);

CREATE FUNCTION set_updated_at_repair_clients() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER repair_clients_set_updated_at BEFORE UPDATE ON repair_clients
  FOR EACH ROW EXECUTE FUNCTION set_updated_at_repair_clients();

