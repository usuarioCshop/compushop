-- 1) Quitar el CHECK de status para que los estados salgan del catalogo.
DO $$
DECLARE
  con record;
BEGIN
  FOR con IN
    SELECT conname
    FROM pg_constraint
    WHERE conrelid = 'technical_repairs'::regclass
      AND contype = 'c'
      AND pg_get_constraintdef(oid) LIKE '%status%'
  LOOP
    EXECUTE format('ALTER TABLE technical_repairs DROP CONSTRAINT %I', con.conname);
  END LOOP;
END $$;

-- 2) Catalogo generico de articulos, marcas y estados.
CREATE TABLE repair_catalog_items (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type       TEXT NOT NULL CHECK (type IN ('article', 'brand', 'status')),
  name       TEXT NOT NULL,
  is_active  BOOLEAN NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (type, name)
);

CREATE INDEX repair_catalog_items_type_idx ON repair_catalog_items (type);

