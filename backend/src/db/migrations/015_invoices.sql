-- Facturación: cabecera e ítems.
-- Número correlativo ascendente, único y no reutilizable.
CREATE TABLE invoices (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number           TEXT NOT NULL UNIQUE, -- correlativo ej 00000001
  status           TEXT NOT NULL DEFAULT 'borrador' CHECK (status IN ('borrador', 'emitida', 'anulada')),
  billing_client_id INTEGER REFERENCES billing_clients (id) ON DELETE SET NULL,
  -- Snapshots para integridad histórica
  issuer_snapshot   jsonb NOT NULL DEFAULT '{}'::jsonb,
  receiver_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb,
  currency         TEXT NOT NULL DEFAULT 'ARS',
  subtotal         numeric(12,2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
  tax_total        numeric(12,2) NOT NULL DEFAULT 0 CHECK (tax_total >= 0),
  discount_total   numeric(12,2) NOT NULL DEFAULT 0 CHECK (discount_total >= 0),
  total            numeric(12,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
  notes            TEXT,
  created_by       INTEGER REFERENCES users (id) ON DELETE SET NULL,
  issued_at        timestamptz,
  voided_at        timestamptz,
  void_reason      TEXT,
  voided_by        INTEGER REFERENCES users (id) ON DELETE SET NULL,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE invoice_items (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id     INTEGER NOT NULL REFERENCES invoices (id) ON DELETE CASCADE,
  source_type    TEXT NOT NULL CHECK (source_type IN ('product', 'repair', 'manual')),
  product_id     INTEGER REFERENCES products (id) ON DELETE SET NULL,
  repair_id      INTEGER REFERENCES technical_repairs (id) ON DELETE SET NULL,
  description    TEXT NOT NULL,
  quantity       numeric(12,2) NOT NULL CHECK (quantity > 0),
  unit_price     numeric(12,2) NOT NULL DEFAULT 0 CHECK (unit_price >= 0),
  vat_rate       numeric(5,2) NOT NULL DEFAULT 0 CHECK (vat_rate >= 0 AND vat_rate <= 100),
  vat_amount     numeric(12,2) NOT NULL DEFAULT 0 CHECK (vat_amount >= 0),
  discount       numeric(12,2) NOT NULL DEFAULT 0 CHECK (discount >= 0),
  line_subtotal  numeric(12,2) NOT NULL DEFAULT 0 CHECK (line_subtotal >= 0),
  line_total     numeric(12,2) NOT NULL DEFAULT 0 CHECK (line_total >= 0),
  metadata       jsonb,
  created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX invoices_status_idx ON invoices (status);
CREATE INDEX invoices_client_idx ON invoices (billing_client_id);
CREATE INDEX invoices_created_at_idx ON invoices (created_at DESC);
CREATE INDEX invoices_number_idx ON invoices (number);
CREATE INDEX invoice_items_invoice_idx ON invoice_items (invoice_id);
CREATE INDEX invoice_items_repair_idx ON invoice_items (repair_id);
CREATE INDEX invoice_items_product_idx ON invoice_items (product_id);

CREATE TRIGGER invoices_set_updated_at BEFORE UPDATE ON invoices
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
