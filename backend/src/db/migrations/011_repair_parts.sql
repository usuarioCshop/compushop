-- Fase 3 de servicio tecnico:
--   * diagnostico y mano de obra en la reparacion,
--   * repuestos usados tomados del catalogo de productos, con cantidad y
--     precio unitario historico.
-- El stock de products es la fuente de verdad: el backend lo descuenta y lo
-- devuelve dentro de transacciones al guardar, editar o borrar la reparacion.
-- El runner de migraciones ya envuelve este archivo en una transaccion.

ALTER TABLE technical_repairs
  ADD COLUMN diagnosis TEXT,
  ADD COLUMN labor_price NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (labor_price >= 0);

CREATE TABLE repair_parts (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  repair_id   INTEGER NOT NULL REFERENCES technical_repairs (id) ON DELETE CASCADE,
  product_id  INTEGER NOT NULL REFERENCES products (id) ON DELETE RESTRICT,
  description TEXT NOT NULL,
  quantity    INTEGER NOT NULL CHECK (quantity > 0),
  unit_price  NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (unit_price >= 0),
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (repair_id, product_id)
);

CREATE INDEX repair_parts_repair_id_idx ON repair_parts (repair_id);
CREATE INDEX repair_parts_product_id_idx ON repair_parts (product_id);

CREATE FUNCTION set_updated_at_repair_parts() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER repair_parts_set_updated_at BEFORE UPDATE ON repair_parts
  FOR EACH ROW EXECUTE FUNCTION set_updated_at_repair_parts();
