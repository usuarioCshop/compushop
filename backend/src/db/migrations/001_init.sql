-- Compushop — esquema inicial para Postgres.
--
-- Diferencias deliberadas respecto del esquema SQLite anterior:
--   * id es IDENTITY con BY DEFAULT: permite conservar ids en una importacion
--     futura, cosa que GENERATED ALWAYS prohibiria.
--   * price / total son numeric(12,2): dinero exacto, no float.
--   * created_at / updated_at / expires_at son timestamptz, no TEXT.
--   * is_active / is_read / used son boolean, no INTEGER 0/1.
--   * products.specs es jsonb, no TEXT con JSON adentro.
--   * Las claves foraneas ahora se HACEN CUMPLIR (en SQLite quedaban declaradas
--     pero sin efecto). Cada una declara que pasa al borrar el padre:
--       - order_items copia nombre y precio del producto, o sea que es el
--         registro historico del pedido: perder el producto o el servicio no
--         debe borrar la linea. SET NULL.
--       - borrar un usuario no debe borrar sus pedidos. SET NULL.
--       - las lineas de un pedido si mueren con el pedido. CASCADE.
--       - los reseteos de contrasena son efimeros. CASCADE.
--       - borrar una categoria deja sus productos sin categoria. SET NULL.

CREATE TABLE users (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT NOT NULL,
  email      TEXT NOT NULL UNIQUE,
  password   TEXT NOT NULL,
  dni        TEXT UNIQUE,
  role       TEXT NOT NULL DEFAULT 'customer' CHECK (role IN ('admin', 'customer')),
  phone      TEXT,
  address    TEXT,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE categories (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        TEXT NOT NULL,
  slug        TEXT NOT NULL UNIQUE,
  description TEXT,
  image       TEXT,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE products (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        TEXT NOT NULL,
  slug        TEXT NOT NULL UNIQUE,
  description TEXT,
  price       numeric(12,2) NOT NULL CHECK (price >= 0),
  stock       INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
  category_id INTEGER REFERENCES categories (id) ON DELETE SET NULL,
  brand       TEXT,
  image       TEXT,
  specs       jsonb,
  is_active   boolean NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE services (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        TEXT NOT NULL,
  slug        TEXT NOT NULL UNIQUE,
  description TEXT,
  price       numeric(12,2) NOT NULL CHECK (price >= 0),
  duration    TEXT,
  image       TEXT,
  is_active   boolean NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE orders (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id          INTEGER REFERENCES users (id) ON DELETE SET NULL,
  order_number     TEXT NOT NULL,
  status           TEXT NOT NULL DEFAULT 'confirmed'
                     CHECK (status IN ('pending', 'confirmed', 'processing', 'shipped', 'cancelled', 'delivered')),
  total            numeric(12,2) NOT NULL CHECK (total >= 0),
  shipping_address TEXT,
  notes            TEXT,
  customer_name    TEXT NOT NULL,
  customer_email   TEXT NOT NULL,
  customer_phone   TEXT,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE order_items (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id   INTEGER NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  product_id INTEGER REFERENCES products (id) ON DELETE SET NULL,
  service_id INTEGER REFERENCES services (id) ON DELETE SET NULL,
  name       TEXT NOT NULL,
  price      numeric(12,2) NOT NULL CHECK (price >= 0),
  quantity   INTEGER NOT NULL CHECK (quantity > 0),
  type       TEXT NOT NULL CHECK (type IN ('product', 'service'))
);

CREATE TABLE contact_messages (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT,
  email      TEXT,
  phone      TEXT,
  subject    TEXT,
  message    TEXT NOT NULL,
  is_read    boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE settings (
  key        TEXT PRIMARY KEY,
  value      TEXT,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE password_resets (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  token      TEXT NOT NULL UNIQUE,
  expires_at timestamptz NOT NULL,
  used       boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Indices de las consultas reales de la API (listados, filtros y claves
-- foraneas). Los slug y los email ya quedan indexados por sus restricciones
-- UNIQUE.
CREATE INDEX products_category_id_idx ON products (category_id);
CREATE INDEX products_active_created_at_idx ON products (is_active, created_at DESC);
CREATE INDEX services_active_idx ON services (is_active);
CREATE INDEX orders_user_id_idx ON orders (user_id);
CREATE INDEX orders_created_at_idx ON orders (created_at DESC);
CREATE INDEX order_items_order_id_idx ON order_items (order_id);
CREATE INDEX contact_messages_unread_idx ON contact_messages (is_read, created_at DESC);
CREATE INDEX password_resets_user_id_idx ON password_resets (user_id);

-- updated_at a cargo de la base, no de cada UPDATE escrito a mano: es el unico
-- lugar donde no se puede olvidar.
CREATE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER users_set_updated_at BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER products_set_updated_at BEFORE UPDATE ON products
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER services_set_updated_at BEFORE UPDATE ON services
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER orders_set_updated_at BEFORE UPDATE ON orders
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER settings_set_updated_at BEFORE UPDATE ON settings
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
