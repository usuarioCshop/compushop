-- Clientes propios de facturación.
-- Se pueden importar datos desde repair_clients (servicio técnico) o users (compras online).
CREATE TABLE billing_clients (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           TEXT NOT NULL,
  doc_type       TEXT, -- DNI, CUIT, etc.
  doc_number     TEXT,
  condicion_iva  TEXT, -- Responsable Inscripto, Monotributo, Consumidor Final, Exento, etc.
  address        TEXT,
  email          TEXT,
  phone          TEXT,
  source_type    TEXT, -- repair_client | user | manual
  source_id      INTEGER,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX billing_clients_name_idx ON billing_clients (name);
CREATE INDEX billing_clients_doc_idx ON billing_clients (doc_number);
CREATE INDEX billing_clients_source_idx ON billing_clients (source_type, source_id);

CREATE TRIGGER billing_clients_set_updated_at BEFORE UPDATE ON billing_clients
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
