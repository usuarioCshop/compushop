-- 018_caja.sql (propuesta) — Bloque 3 Caja MVP
-- Crea tablas de caja (sesiones/cierres, categorías, movimientos), ajusta invoices
-- para registrar forma de cobro al facturar y agrega estado de reparación
-- "cobrado s/facturacion" en el catálogo.

-- 1) Sesiones/cierres diarios de caja (apertura, arqueo, diferencias)
CREATE TABLE IF NOT EXISTS cash_sessions (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_date     date NOT NULL,
  status           text NOT NULL CHECK (status IN ('abierta', 'cerrada')),
  opening_balance  numeric(12,2) NOT NULL DEFAULT 0 CHECK (opening_balance >= 0),
  counted_cash     numeric(12,2) CHECK (counted_cash >= 0),
  expected_cash    numeric(12,2),
  difference       numeric(12,2),
  totals_snapshot  jsonb,
  notes            text,
  opened_by        integer REFERENCES users(id) ON DELETE SET NULL,
  opened_at        timestamptz NOT NULL DEFAULT now(),
  closed_by        integer REFERENCES users(id) ON DELETE SET NULL,
  closed_at        timestamptz,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT cash_sessions_closed_fields_chk CHECK (
    status = 'abierta'
    OR (counted_cash IS NOT NULL AND expected_cash IS NOT NULL AND difference IS NOT NULL AND closed_at IS NOT NULL)
  )
);

CREATE UNIQUE INDEX IF NOT EXISTS cash_sessions_date_uq ON cash_sessions (session_date);
-- A lo sumo una sesión abierta a la vez
CREATE UNIQUE INDEX IF NOT EXISTS cash_sessions_one_open_uq
  ON cash_sessions (status) WHERE status = 'abierta';

CREATE TRIGGER cash_sessions_set_updated_at
  BEFORE UPDATE ON cash_sessions
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 2) Categorías de caja (principalmente egresos), creables desde modal
CREATE TABLE IF NOT EXISTS cash_categories (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       text NOT NULL,
  is_active  boolean NOT NULL DEFAULT true,
  is_default boolean NOT NULL DEFAULT false,
  created_by integer REFERENCES users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS cash_categories_name_uq
  ON cash_categories (lower(btrim(name)));

CREATE TRIGGER cash_categories_set_updated_at
  BEFORE UPDATE ON cash_categories
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

