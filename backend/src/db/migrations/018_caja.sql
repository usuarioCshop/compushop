-- 3) Movimientos unificados de caja (ingresos mixtos y egresos)
CREATE TABLE IF NOT EXISTS cash_movements (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  movement_type   text NOT NULL CHECK (movement_type IN ('ingreso', 'egreso')),
  origin_type     text NOT NULL CHECK (origin_type IN ('factura', 'pedido', 'reparacion', 'otro', 'egreso_manual')),
  origin_id       integer,
  cash_session_id integer REFERENCES cash_sessions(id) ON DELETE SET NULL,
  movement_date   date NOT NULL,
  amount          numeric(12,2) NOT NULL CHECK (amount > 0),
  status          text NOT NULL CHECK (status IN (
                    'cobrado', 'pendiente_verificacion', 'pendiente_cobro', 'registrado', 'anulado'
                  )),
  payment_method  text NOT NULL CHECK (payment_method IN ('efectivo', 'transferencia', 'cuenta_corriente', 'otro')),
  description     text NOT NULL,
  category_id     integer REFERENCES cash_categories(id) ON DELETE SET NULL,
  reference       text,
  counterparty    text,
  notes           text,
  accredited_at   timestamptz,
  accredited_by   integer REFERENCES users(id) ON DELETE SET NULL,
  voided_at       timestamptz,
  voided_by       integer REFERENCES users(id) ON DELETE SET NULL,
  void_reason     text,
  created_by      integer REFERENCES users(id) ON DELETE SET NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  metadata        jsonb,
  CONSTRAINT cash_movements_type_status_chk CHECK (
    (movement_type = 'ingreso' AND status IN ('cobrado', 'pendiente_verificacion', 'pendiente_cobro', 'anulado'))
    OR
    (movement_type = 'egreso' AND status IN ('registrado', 'anulado'))
  ),
  CONSTRAINT cash_movements_type_origin_chk CHECK (
    (movement_type = 'ingreso' AND origin_type IN ('factura', 'pedido', 'reparacion', 'otro'))
    OR
    (movement_type = 'egreso' AND origin_type = 'egreso_manual')
  ),
  CONSTRAINT cash_movements_origin_id_chk CHECK (
    (origin_type IN ('factura', 'pedido', 'reparacion') AND origin_id IS NOT NULL)
    OR
    (origin_type IN ('otro', 'egreso_manual') AND origin_id IS NULL)
  ),
  CONSTRAINT cash_movements_payment_chk CHECK (
    (movement_type = 'ingreso' AND payment_method IN ('efectivo', 'transferencia', 'cuenta_corriente'))
    OR
    (movement_type = 'egreso' AND payment_method IN ('efectivo', 'transferencia', 'otro'))
  ),
  CONSTRAINT cash_movements_category_chk CHECK (
    (movement_type = 'egreso' AND category_id IS NOT NULL)
    OR
    (movement_type = 'ingreso')
  ),
  CONSTRAINT cash_movements_accredited_chk CHECK (
    (status = 'cobrado' AND movement_type = 'ingreso' AND payment_method IN ('transferencia', 'cuenta_corriente') AND accredited_at IS NOT NULL)
    OR
    (status = 'cobrado' AND movement_type = 'ingreso' AND payment_method = 'efectivo')
    OR
    (status <> 'cobrado')
  )
);

CREATE INDEX IF NOT EXISTS cash_movements_date_idx ON cash_movements (movement_date DESC);
CREATE INDEX IF NOT EXISTS cash_movements_type_status_idx ON cash_movements (movement_type, status);
CREATE INDEX IF NOT EXISTS cash_movements_origin_idx ON cash_movements (origin_type, origin_id);
CREATE INDEX IF NOT EXISTS cash_movements_session_idx ON cash_movements (cash_session_id);
CREATE INDEX IF NOT EXISTS cash_movements_category_idx ON cash_movements (category_id);
CREATE INDEX IF NOT EXISTS cash_movements_payment_idx ON cash_movements (payment_method);

-- Idempotencia: un ingreso activo por origen factura/pedido/reparación
CREATE UNIQUE INDEX IF NOT EXISTS cash_movements_income_origin_uq
  ON cash_movements (origin_type, origin_id)
  WHERE movement_type = 'ingreso'
    AND origin_type IN ('factura', 'pedido', 'reparacion')
    AND status <> 'anulado';

CREATE TRIGGER cash_movements_set_updated_at
  BEFORE UPDATE ON cash_movements
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

