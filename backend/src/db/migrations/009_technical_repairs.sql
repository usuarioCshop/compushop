-- Ordenes de reparacion / servicio tecnico (solo rol tecnico).
-- Agrega el rol 'tecnico' al CHECK de usuarios y crea la tabla de reparaciones.
BEGIN;

-- Rol Tecnico disponible para usuarios.
ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check;
ALTER TABLE users ADD CONSTRAINT users_role_check CHECK (role IN ('admin', 'customer', 'tecnico'));

CREATE TABLE technical_repairs (
  id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_number      TEXT NOT NULL,                 -- Nº de Boleta
  status             TEXT NOT NULL DEFAULT 'pendiente'
                     CHECK (status IN ('pendiente', 'en_proceso', 'reparado', 'entregado', 'cancelado')),
  received_at        timestamptz NOT NULL DEFAULT now(),
  client_name        TEXT NOT NULL,
  client_address     TEXT,
  client_id          TEXT,                          -- Num ID / DNI
  client_email       TEXT,
  client_phone       TEXT,
  article            TEXT,                          -- Articulo (ej. CPU)
  brand              TEXT,                          -- Marca
  model              TEXT,                          -- Modelo
  serial_number      TEXT,                          -- Nº de serie
  damage_reported    TEXT NOT NULL,                 -- Daño reportado
  notes              TEXT,                          -- Notas
  image_url          TEXT,                          -- URL de la foto del equipo
  probable_repair_date timestamptz,                 -- Fecha probable de reparación
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX technical_repairs_ticket_number_idx ON technical_repairs (ticket_number);
CREATE INDEX technical_repairs_status_idx ON technical_repairs (status);
CREATE INDEX technical_repairs_created_at_idx ON technical_repairs (created_at DESC);

CREATE FUNCTION set_updated_at_technical_repairs() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER technical_repairs_set_updated_at BEFORE UPDATE ON technical_repairs
  FOR EACH ROW EXECUTE FUNCTION set_updated_at_technical_repairs();

COMMIT;
